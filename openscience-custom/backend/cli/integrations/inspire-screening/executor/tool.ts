export const schema = z.object({
  action: z.enum(["create", "approve", "status", "list", "cancel", "wake", "report", "download", "resume_delivery", "select_refinement", "diagnose_preparation", "diagnose_refinement", "plan_refinement", "approve_refinement", "cancel_refinement", "refinement_status", "refinement_report", "resume_refinement_delivery"]),
  artifact: artifact.optional().describe("For download only: exact phase and name from this task's verified artifact inventory; never an arbitrary path."),
  selection_policy: selection.optional(),
  task_id: z.string().regex(/^screen-[a-f0-9]{24}$/).optional(),
  ...createFields,
}).strict().superRefine((input, ctx) => {
  if (input.action === "create") {
    if (input.artifact) ctx.addIssue({ code: "custom", message: "Artifact delivery requires a completed task" })
    if (input.selection_policy) ctx.addIssue({ code: "custom", message: "Refinement selection needs completed core evidence" })
    if (input.request === undefined) ctx.addIssue({ code: "custom", message: "Original user request is required" })
    if (input.task_id) ctx.addIssue({ code: "custom", message: "New task IDs are generated by the host" })
  } else {
    if (!["list"].includes(input.action) && !input.task_id) ctx.addIssue({ code: "custom", message: "Task ID required" })
    const allowed = input.action === "select_refinement" ? ["action", "task_id", "selection_policy"] :
      input.action === "download" ? ["action", "task_id", "artifact"] : ["action", "task_id"]
    if (input.action === "download" && !input.artifact) ctx.addIssue({ code: "custom", message: "Exact report artifact required" })
    if (input.action === "select_refinement" && !input.selection_policy) ctx.addIssue({ code: "custom", message: "Explicit refinement policy is required" })
    if (Object.keys(input).some((key) => !allowed.includes(key))) ctx.addIssue({ code: "custom", message: "Saved task plans cannot be edited via lifecycle actions" })
  }
})

export function summary(task: Task, stages?: Stage[]) {
  return { task_id: task.id, state: task.state, digest: task.digest, request: task.plan.request, origin: task.plan.origin,
    target: task.plan.target, site: task.plan.site, library: task.plan.library, scope: task.plan.scope,
    target_parameters: task.plan.target_parameters ?? null,
    max_records: task.plan.max_records, shortlist: task.plan.shortlist, max_points: task.plan.max_points,
    resource_plan: task.plan.automation ?? null,
    execution: { controller: "platform-daemon", mode: "automatic-after-native-approval",
      approval_recorded: !!task.approval, snapshot_at: Date.now(),
      note: "This is a point-in-time snapshot. After native approval the host requests its background observer automatically; WAITING does not mean the user must call wake. Use status for current progress. wake is recovery only, not another approval or a compute retry. SUBMITTED awaits observation; QUEUED means pending; RUNNING requires a live running observation." },
    delivery_policy: task.plan.delivery,
    stages: stages?.map((stage) => ({ phase: stage.phase, state: stage.state, job: stage.handle,
      planned_job: stage.name, submitted_at: stage.submitted, error: stage.error,
      verified: stage.manifest ? JSON.parse(stage.manifest) : null })),
    resources: task.plan.steps.map((step) => ({ phase: step.phase, minutes: step.minutes, ...step.resource })),
    output: `${task.plan.runtime.root}/tasks/${task.id}`,
    failed_stage: stages?.find((stage) => stage.state === "FAILED")?.phase,
    error: task.error ?? stages?.find((stage) => stage.error)?.error ?? null,
    warning: "Counts are runtime evidence, not predicted hits. Core pipeline only; uncertainty/refinement is a subsequent approved stage. No legacy pilot reuse." }
}

export function manualDeliveryLimit(task: Task, input: z.infer<typeof artifact>, files: ReturnType<typeof publications>) {
  const policy = task.plan.delivery
  if (!policy) return undefined
  // A second model-triggered transfer must not race the queue's shared budget.
  // Once published, retrieving that same file does not add a new inventory item.
  if (!files.some((file) => file.phase === input.phase && file.name === input.name)) {
    throw new Error("This approved policy uses the automatic delivery queue; inspect status or resume_delivery instead of bypassing it with download")
  }
  const other = files.filter((file) => file.phase !== input.phase || file.name !== input.name)
  return Math.max(0, Math.min(policy.max_file_bytes, policy.max_total_bytes - other.reduce((sum, file) => sum + file.bytes, 0)))
}

// One persisted view for status/list, aligned with the native card. Reading this
// snapshot never invokes the remote diagnostic or treats it as scientific success.
export function snapshot(store: Store, task: Task) {
  return { ...summary(task, store.stages(task.id)), delivery: deliveryStatus(store, task),
    refinement_executions: refinementExecutions(store, task),
    selection: selectionSnapshot(store, task), preparation_diagnostic: preparationSnapshot(store, task),
    refinement_environment: refinementDiagnosticSnapshot(store, task), refinement_proposal: presentRefinement(refinementProposalSnapshot(store, task)) }
}

export async function execute(input: unknown, context: ToolContext, source?: BoundRequest, workflow?: WorkflowReference) {
  const parsed = workflow ? undefined : schema.parse(input)
  const store = await open()
  try {
    const args = parsed ?? schema.parse(workflowTaskArguments(store, workflow!, context, input))
    if (args.action === "list") return JSON.stringify(store.list(context.directory).map((task) => snapshot(store, task)))
    if (args.action === "create") {
      requireDockingEngine("carsidock-cov") // Current screening plan requires this suspended engine.
      if (!source) throw new Error("Create requires the platform-bound original user message")
      const intake = await clarify(store, source, args, context, true)
      const admission = targetAdmission(intake.values.target_parameters!)
      if (!admission.supported) return JSON.stringify({ state: "TARGET_CONFIGURATION_REQUIRED", intake_id: intake.id,
        target_parameters: intake.values.target_parameters, reason: admission.reason, compute_submitted: false })
      const config = await settings()
      const transport = new Inspire(config.connection)
      const assets = z.object({ assets: z.record(z.string(), z.string()), runtime: planSchema.shape.runtime })
        .passthrough().parse(await transport.remote(config.runtime, ["snapshot"]))
      if (digest(assets.runtime) !== digest(config.runtime)) throw new Error("Remote worker/runtime identity differs from host configuration")
      const cpu = resource.parse({ ...config.cpu, points_per_hour: 0 })
      const gpu = resource.parse({ ...config.gpu, points_per_hour: 0 })
      const [cpuRate, gpuRate] = await Promise.all([transport.live(cpu), transport.live(gpu)])
      const initial = choose({ screening_mode: intake.values.screening_mode,
        requested_mode: intake.values.requested_mode, max_points: intake.values.max_points }, { cpu: cpuRate, gpu: gpuRate })
      const intent = initial.requires_confirmation
        ? await confirmPlanning(store, intake.id, initial, context)
        : intake.values
      const plan = compileScreening({ intent, source, directory: context.directory, session: context.sessionID,
        assets: assets.assets, runtime: config.runtime, connection: config.connection,
        cpu: { ...cpu, points_per_hour: cpuRate }, gpu: { ...gpu, points_per_hour: gpuRate } })
      // These calls resolve actual image/Slurm/quota fields but allocate nothing.
      for (const [ordinal, step] of plan.steps.entries()) {
        const stage: Stage = { task_id: plan.id, ordinal, phase: step.phase, name: `${plan.id}-${step.phase}`,
          state: "WAITING", handle: null, manifest: null, error: null, submitted: null }
        await transport.call(createArgs(plan, stage, true))
      }
      const task = await propose(store, plan, context, intake.id)
      await ensureDaemon(store)
      return JSON.stringify({ ...summary(task, store.stages(task.id)), intake_id: intake.id, approval_required: false,
        observer_start_requested: true,
        structure: "1M17 A:CYS:773, registered mapping to EGFR C797 (+24); disclosed receptor, not a silent template switch",
        cost_note: "Live quota rate × bounded stage runtime, points not USD; not an account-wide billing cap" })
    }
    const task = store.get(args.task_id!)
    if (task.plan.directory !== context.directory) throw new Error("Task belongs to another project")
    if (args.action === "cancel_refinement") {
      await advanceNativeRefinement(store, task, "cancel", context)
      return JSON.stringify({ task_id: task.id, executions: refinementExecutions(store, task),
        note: "取消意图已保存；已提交作业须由后台核实终止，不将停止请求当作已停止。" })
    }
    if (args.action === "approve_refinement") {
      const workflow = await advanceNativeRefinement(store, task, "approve", context)
      return JSON.stringify({ task_id: task.id, workflow, observer_start_requested: true,
        note: "一次原生审批已保存；后台核验并推进所批两阶段，提交状态仍以真实作业回读为准。" })
    }
    if (args.action === "refinement_report") {
      const result = await readRefinementReport(store, task, context)
      const failure = !result.report_ready && 'stages' in result && result.stages.some((stage) => ["FAILED", "CANCELLED", "NEEDS_REVIEW"].includes(stage.state))
        ? await readRefinementFailure(store, task, context) : null
      store.event(task.id, "refinement_report_read", result)
      if (failure) store.event(task.id, "refinement_failure_read", failure)
      context.metadata({ title: result.report_ready ? "AF3 / CovDock 综合评估（源文件已核验）" : "AF3 / CovDock 综合评估尚不可用",
        metadata: { task_id: task.id, report_ready: result.report_ready, verification: result.verification } })
      await ensureDelivery(store)
      const delivery = refinementDeliveries(store, task)
      return JSON.stringify({ ...result, failure: failure ? refinementFailureSummary(failure) : null, delivery,
        ...refinementPublicationStatus(result.report, delivery) })
    }
    if (args.action === "resume_refinement_delivery") {
      if (task.plan.session !== context.sessionID) throw new Error("Refinement delivery belongs to another conversation")
      const saved = refinementDeliveries(store, task)
      for (const row of saved.filter((item) => item.state === "PAUSED")) new RefinementDelivery(store).resume(row.workflow_id, task)
      await ensureDelivery(store)
      return JSON.stringify({ task_id: task.id, delivery: refinementDeliveries(store, task), compute_restarted: false })
    }
    if (args.action === "refinement_status") {
      if (task.plan.session !== context.sessionID) throw new Error("Refinement status belongs to another conversation")
      // No accumulated core events/manifests: they can hide this small current
      // proposal behind generic tool-output truncation and an inaccessible file.
      return JSON.stringify({ task_id: task.id, core_state: task.state,
        ...presentRefinement(refinementProposalSnapshot(store, task)), execution_draft: refinementDraftSnapshot(store, task.id),
        delivery: refinementDeliveries(store, task), executions: refinementExecutions(store, task), report_ready: false, compute_restarted: false })
    }
    if (args.action === "plan_refinement") {
      if (task.plan.session !== context.sessionID) throw new Error("Refinement planning belongs to another conversation")
      if (!source) throw new Error("Refinement planning requires the platform-bound original user request")
      const proposal = presentRefinement(await planRefinement(store, task, context.abort))
      context.abort.throwIfAborted()
      const execution_draft = await prepareRefinementDraft(store, task.id, source)
      context.metadata({ title: "AF3 / CovDock 精筛方案（未批准、未执行）", metadata: { task_id: task.id, proposal, execution_draft } })
      return JSON.stringify({ ...proposal, execution_draft, report_ready: false, compute_restarted: false })
    }
    if (args.action === "diagnose_refinement") {
      if (task.plan.session !== context.sessionID) throw new Error("Refinement diagnosis belongs to another conversation")
      const diagnosis = await diagnoseRefinement(store, task.id, context.abort)
      context.metadata({ title: "AF3 / CovDock 环境诊断（未启动精筛）", metadata: { task_id: task.id, diagnosis } })
      return JSON.stringify({ diagnosis, report_ready: false, compute_restarted: false })
    }
    if (args.action === "diagnose_preparation") {
      if (task.plan.session !== context.sessionID) throw new Error("Diagnosis belongs to another conversation")
      const diagnosis = await diagnosePreparation(store, task.id, undefined, context.abort)
      const presentation = await new Progress(store).publish(store.get(task.id))
      return JSON.stringify({ diagnosis, presentation, report_ready: false, compute_restarted: false })
    }
    if (args.action === "resume_delivery") {
      if (task.plan.session !== context.sessionID) throw new Error("Delivery belongs to another conversation")
      const delivery = new DeliveryQueue(store, new Inspire(task.plan.connection)).resume(task)
      await ensureDaemon(store)
      return JSON.stringify({ task_id: task.id, delivery, compute_restarted: false })
    }
    if (args.action === "download") {
      const remaining = manualDeliveryLimit(task, args.artifact!, publications(store, task))
      const delivered = await deliverArtifact(task, store.stages(task.id), args.artifact!, context, new Inspire(task.plan.connection), remaining)
      store.event(task.id, "artifact_delivered", delivered)
      const published = await new Publications(store).publish(task, delivered).then(
        (result) => ({ publication_status: "published", result }),
        (error: unknown) => ({ publication_status: "unavailable", reason: error instanceof Error ? error.message : "Result publication unavailable" }))
      await new Progress(store).publish(task).catch(() => undefined)
      return JSON.stringify({ ...delivered, ...published })
    }
    if (args.action === "select_refinement") {
      const result = await selectRefinementProposal(store, task, args.selection_policy!, new Inspire(task.plan.connection), context.abort)
      // Publication does not invoke a model or grant resources. The observer can
      // retry a failed UI delivery from the already-persisted event.
      const presentation = await new Progress(store).publish(store.get(task.id)).catch(() => ({ delivered: false, reason: "Progress publication unavailable" }))
      return JSON.stringify({ ...result, presentation })
    }
    if (args.action === "approve" || args.action === "cancel" || args.action === "wake")
      await advanceNativeTask(store, task.id, args.action, context)
    const current = store.get(task.id)
    const stages = store.stages(task.id)
    const report = args.action === "report" ? current.state === "FAILED"
      ? await readFailureReport(store, current.id, new Inspire(current.plan.connection), context.abort)
      : await readReport(current, stages, new Inspire(current.plan.connection)) : undefined
    if (report) store.event(task.id, "report_read", report)
    return JSON.stringify({ ...snapshot(store, current), events: store.events(task.id).slice(-20), ...report })
  } finally { store.close() }
}
